"""Reproducible as-of resolution; archive generated hash locks with each release.

Run with uv==0.13.4 available. Network/index failure is fatal; no unlocked fallback.
"""

import argparse
import subprocess
import tempfile
from pathlib import Path

UV_VERSION = "0.13.4"
CUTOFF = "2026-11-08T00:00:00Z"
RUNTIME_LOCK = Path("requirements-linux.lock")


def commands(platform: str, benchmark: bool = False) -> list[list[str]]:
    common = ["uv", "pip", "compile", "--python-version", "3.12", "--python-platform", platform,
              "--exclude-newer", CUTOFF, "--generate-hashes", "--upgrade"]
    result = [
        [*common, "requirements.txt", "--output-file", ".locks/runtime.txt"],
        [*common, "requirements-dev.txt", "requirements-dashboard.txt", "--constraint", ".locks/runtime.txt",
         "--output-file", ".locks/ci.txt"],
    ]
    if benchmark:
        result.append([
            *common, "requirements-benchmark.txt", "--constraint", ".locks/ci.txt",
            "--output-file", ".locks/benchmark.txt",
        ])
    return result


def linux_runtime_lock() -> bytes:
    """Resolve only runtime dependencies; temporary output paths cannot affect bytes."""
    Path(".locks").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="linux-runtime-", dir=".locks") as directory:
        output = Path(directory) / "runtime.txt"
        command = commands("linux")[0]
        command[-1] = str(output)
        subprocess.run([*command, "--no-header", "--no-annotate"], check=True, timeout=300)
        header = (
            "# Linux / Python 3.12 runtime only. Generated by scripts/lock_dependencies.py.\n"
            f"# uv=={UV_VERSION}; exclude-newer={CUTOFF}\n"
        ).encode()
        return header + output.read_bytes()


def check_runtime_lock(path: Path, first: bytes, second: bytes) -> None:
    """Check mode never rewrites the release artifact or accepts unstable resolution."""
    if first != second:
        raise SystemExit("Linux runtime resolution is not reproducible; review the resolver/index state.")
    if not path.is_file() or path.read_bytes() != first:
        raise SystemExit("Linux runtime lock is missing or stale; run --platform linux --update-runtime-lock and review it.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", default="linux", choices=("linux", "windows", "macos"))
    parser.add_argument("--benchmark", action="store_true", help="Also generate the optional benchmark hash lock.")
    release = parser.add_mutually_exclusive_group()
    release.add_argument("--update-runtime-lock", action="store_true", help="Write the tracked Linux runtime lock.")
    release.add_argument("--check-runtime-lock", action="store_true", help="Resolve twice and verify the tracked Linux lock.")
    args = parser.parse_args()
    if (args.update_runtime_lock or args.check_runtime_lock) and (args.platform != "linux" or args.benchmark):
        parser.error("Release runtime lock modes require --platform linux and cannot be combined with --benchmark.")
    if subprocess.check_output(["uv", "--version"], text=True).split()[1] != UV_VERSION:
        raise SystemExit(f"Install uv=={UV_VERSION} before regenerating locks.")
    if args.update_runtime_lock:
        RUNTIME_LOCK.write_bytes(linux_runtime_lock())
        return
    if args.check_runtime_lock:
        check_runtime_lock(RUNTIME_LOCK, linux_runtime_lock(), linux_runtime_lock())
        print("Committed Linux runtime lock matches runtime inputs and two independent resolutions.")
        return
    Path(".locks").mkdir(exist_ok=True)
    for command in commands(args.platform, args.benchmark):
        subprocess.run(command, check=True, timeout=300)


if __name__ == "__main__":
    main()
